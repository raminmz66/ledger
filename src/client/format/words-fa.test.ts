import { describe, expect, it } from 'vitest'
import { numberToWordsFa } from './words-fa'

describe('numberToWordsFa', () => {
  it.each([
    [0, 'صفر'],
    [1, 'یک'],
    [11, 'یازده'],
    [19, 'نوزده'],
    [20, 'بیست'],
    [21, 'بیست و یک'],
    [100, 'صد'],
    [101, 'صد و یک'],
    [250, 'دویست و پنجاه'],
    [500, 'پانصد'],
    [999, 'نهصد و نود و نه'],
    [1000, 'هزار'],
    [1001, 'هزار و یک'],
    [2000, 'دو هزار'],
    [12_345, 'دوازده هزار و سیصد و چهل و پنج'],
    [1_000_000, 'یک میلیون'],
    [2_500_000, 'دو میلیون و پانصد هزار'],
    [1_001_000, 'یک میلیون و هزار'],
    [10_000_000, 'ده میلیون'],
    [1_000_000_000, 'یک میلیارد'],
    [1_000_000_000_000, 'یک تریلیون'],
    [3_456_789_012, 'سه میلیارد و چهارصد و پنجاه و شش میلیون و هفتصد و هشتاد و نه هزار و دوازده'],
  ])('%i → %s', (n, words) => {
    expect(numberToWordsFa(n)).toBe(words)
  })

  it('throws on negatives, floats and values above one trillion', () => {
    for (const bad of [-1, 1.5, 1_000_000_000_001, NaN]) expect(() => numberToWordsFa(bad)).toThrow()
  })
})
